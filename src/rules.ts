import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

export interface ProjectRule {
  id: string;
  title: string;
  globs?: string[];
  keywords?: string[];
  content: string;
  source: string;
  autoGenerated?: boolean;
}

/** Parse frontmatter or header from markdown rule files */
export function parseRuleFile(filePath: string): ProjectRule | null {
  if (!existsSync(filePath)) return null;
  try {
    const raw = readFileSync(filePath, 'utf8');
    // basename(), not split('/'): Windows paths use backslashes, and a split
    // that never matches returns the FULL path as the "filename" (rule ids
    // became absolute paths on win32).
    const filename = basename(filePath) || 'rule';
    const id = filename.replace(/^\./, '').replace(/\.(md|mdc)$/, '') || filename;
    let content = raw;
    let title = id;
    let globs: string[] | undefined;
    let keywords: string[] | undefined;
    let autoGenerated = false;

    // Check for YAML-like frontmatter: --- ... ---
    const fmMatch = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
    if (fmMatch) {
      const fm = fmMatch[1];
      content = fmMatch[2].trim();
      for (const line of fm.split('\n')) {
        const [k, ...vParts] = line.split(':');
        if (!k || vParts.length === 0) continue;
        const v = vParts.join(':').trim();
        const key = k.trim();
        if (key === 'title' || key === 'description') title = v.replace(/^['"]|['"]$/g, '');
        if (key === 'globs') {
          try {
            globs = JSON.parse(v);
          } catch {
            globs = v.split(',').map((s) => s.trim().replace(/^['"\[]|['"\]]$/g, '')).filter(Boolean);
          }
        }
        if (key === 'keywords') {
          try {
            keywords = JSON.parse(v);
          } catch {
            keywords = v.split(',').map((s) => s.trim().replace(/^['"\[]|['"\]]$/g, '')).filter(Boolean);
          }
        }
        if (key === 'autoGenerated') autoGenerated = v.toLowerCase() === 'true';
      }
    } else {
      const h1 = raw.match(/^#\s+(.+)$/m);
      if (h1) title = h1[1].trim();
    }

    return { id, title, globs, keywords, content, source: filePath, autoGenerated };
  } catch {
    return null;
  }
}

/** Load all modular rules from .mochi/rules/, .cursor/rules/, .claude/rules/, .cursorrules in cwd */
export function loadRules(projectRoot: string): ProjectRule[] {
  const rules: ProjectRule[] = [];
  const seenSources = new Set<string>();

  const scanDir = (dirPath: string) => {
    if (!existsSync(dirPath)) return;
    try {
      const files = readdirSync(dirPath).filter((f) => f.endsWith('.md') || f.endsWith('.mdc'));
      for (const f of files) {
        const fullPath = join(dirPath, f);
        if (seenSources.has(fullPath)) continue;
        seenSources.add(fullPath);
        const parsed = parseRuleFile(fullPath);
        if (parsed) rules.push(parsed);
      }
    } catch {
      /* ignore read error */
    }
  };

  scanDir(resolve(projectRoot, '.mochi', 'rules'));
  scanDir(resolve(projectRoot, '.cursor', 'rules'));
  scanDir(resolve(projectRoot, '.claude', 'rules'));

  const singleFiles = [
    resolve(projectRoot, '.cursorrules'),
    resolve(projectRoot, '.github', 'copilot-instructions.md'),
  ];
  for (const sf of singleFiles) {
    if (existsSync(sf) && !seenSources.has(sf)) {
      seenSources.add(sf);
      const parsed = parseRuleFile(sf);
      if (parsed) rules.push(parsed);
    }
  }

  return rules;
}

const RULES_SCAN_DIRS = ['.mochi/rules', '.cursor/rules', '.claude/rules'];
const RULES_SINGLE_FILES = ['.cursorrules', '.github/copilot-instructions.md'];

function statFp(path: string): string {
  try {
    const st = statSync(path);
    return `${st.size}:${st.mtimeMs}`;
  } catch {
    return '';
  }
}

/** Fingerprint of everything loadRules() would read: per-directory entry
 *  names + size:mtime per file. Any rule add/edit/delete changes it. */
export function rulesFingerprint(projectRoot: string): string {
  const parts: string[] = [];
  for (const rel of RULES_SCAN_DIRS) {
    const dir = resolve(projectRoot, rel);
    let entries: string[] = [];
    try {
      entries = readdirSync(dir)
        .filter((f) => f.endsWith('.md') || f.endsWith('.mdc'))
        .sort();
    } catch {
      entries = [];
    }
    parts.push(`${rel}[${entries.map((f) => `${f}@${statFp(join(dir, f))}`).join(',')}]`);
  }
  for (const rel of RULES_SINGLE_FILES) {
    parts.push(`${rel}@${statFp(resolve(projectRoot, rel))}`);
  }
  return parts.join('|');
}

const rulesCache = new Map<string, { fp: string; rules: ProjectRule[] }>();

/** loadRules() behind a fingerprint cache. Prompt assembly calls this on
 *  EVERY turn (twice: the stable prompt's rule selection and the volatile
 *  prompt's glob-rule selection), and the uncached version re-scanned three
 *  directories and re-read + re-parsed every rule file per call. The
 *  fingerprint check costs the same readdir listing plus stats — no file
 *  bodies are read and nothing is parsed on a hit. */
export function loadRulesCached(projectRoot: string): ProjectRule[] {
  const fp = rulesFingerprint(projectRoot);
  const hit = rulesCache.get(projectRoot);
  if (hit && hit.fp === fp) return hit.rules;
  const rules = loadRules(projectRoot);
  rulesCache.set(projectRoot, { fp, rules });
  return rules;
}

/** Test hook: drop all cached rule sets. */
export function clearRulesCache(): void {
  rulesCache.clear();
}

/** Filter rules relevant to active file paths or prompt text */
export function selectActiveRules(
  rules: ProjectRule[],
  activeFiles: string[] = [],
  promptText = ''
): ProjectRule[] {
  if (rules.length === 0) return [];
  const textLower = promptText.toLowerCase();

  return rules.filter((r) => {
    // If no triggers specified, rule applies universally
    if ((!r.globs || r.globs.length === 0) && (!r.keywords || r.keywords.length === 0)) {
      return true;
    }

    // Match file extension/glob
    if (r.globs && r.globs.length > 0 && activeFiles.length > 0) {
      for (const g of r.globs) {
        const ext = g.startsWith('*') ? g.slice(1) : g;
        if (activeFiles.some((f) => f.endsWith(ext) || f.includes(ext))) return true;
      }
    }

    // Match keyword
    if (r.keywords && r.keywords.length > 0) {
      for (const kw of r.keywords) {
        if (textLower.includes(kw.toLowerCase())) return true;
      }
    }

    return false;
  });
}

/** Synthesize and save a new rule to .mochi/rules/ */
export function synthesizeRule(
  projectRoot: string,
  ruleName: string,
  title: string,
  content: string,
  opts: { globs?: string[]; keywords?: string[] } = {}
): void {
  const rulesDir = resolve(projectRoot, '.mochi', 'rules');
  if (!existsSync(rulesDir)) mkdirSync(rulesDir, { recursive: true });

  const safeName = ruleName.toLowerCase().replace(/[^a-z0-9_-]/g, '-');
  const filePath = join(rulesDir, `${safeName}.md`);
  const frontmatter = [
    '---',
    `title: "${title}"`,
    opts.globs && opts.globs.length > 0 ? `globs: ${JSON.stringify(opts.globs)}` : null,
    opts.keywords && opts.keywords.length > 0 ? `keywords: ${JSON.stringify(opts.keywords)}` : null,
    'autoGenerated: true',
    '---',
    '',
    content.trim(),
    '',
  ].filter(Boolean).join('\n');

  writeFileSync(filePath, frontmatter, 'utf8');
}
